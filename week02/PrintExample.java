/**
 * Practical 2: PrintExample
 * Course: COS 201 - Computer Programming I
 * Description: Demonstrates print() versus println() output behavior.
 */
public class PrintExample {
    public static void main(String[] args) {
        // print() outputs without appending a new line
        System.out.print("COS ");
        // println() outputs and advances to the next line
        System.out.println("201");
        System.out.println("Java");
    }
}
